SIPMessage::SIPMessage() {}

std::string SIPMessage::to_string() const {
  std::string out;
  out += header->to_string();
  out += "\r\n";
  if (body.size() != 0) out += body;
  return out;
}

void SIPMessage::print() const { std::cout << Util::trim(to_string()) << std::endl; }

std::string SIPMessage::get_transaction_id() {
  // RFC 3261 17.1.3, 17.2.3: a transaction is identified by the top Via's branch and
  // sent-by plus the method. Branch alone can collide across upstream hops.
  if (!header->contains("Via") || !header->contains("CSeq")) {
    throw std::runtime_error("SIPMessage::get_transaction_id requires Via and CSeq");
  }

  auto via = header->headers_map["Via"][0]->as<ViaHeader>();
  auto cseq = header->headers_map["CSeq"][0]->as<CSeqHeader>();

  if (via == nullptr || cseq == nullptr) {
    throw std::runtime_error("SIPMessage::get_transaction_id could not read Via or CSeq");
  }

  // Separators keep distinct triples from concatenating to the same string.
  return via->parameters["branch"] + "|" + via->host + "|" + cseq->method;
}

// Copies by serialising and re-parsing, so every header type is covered without a
// per-type clone.
std::shared_ptr<SIPMessage> SIPMessage::clone() const {
  auto copy = std::make_shared<SIPMessage>();

  copy->header = std::make_shared<SIPHeader>(header->to_string());
  copy->body = body;
  copy->body_length = body_length;

  copy->branch = branch;
  copy->source_port = source_port;
  copy->channel = channel;
  copy->call = call;
  copy->subscriber = subscriber;
  copy->contact = contact;
  copy->authenticated = authenticated;

  return copy;
}

std::shared_ptr<SIPMessage> SIPMessage::generate_response() {
  auto response = std::make_shared<SIPMessage>();

  response->header = std::make_shared<SIPHeader>();
  response->header->type = SIPHeader::Type::Response;
  response->body_length = 0;

  response->channel = channel;
  response->contact = contact;
  response->call = call;

  if (header->contains("From")) {
    response->header->add("From", header->headers_map["From"][0]);
  } else {
    response->header->add("From", "<sip:unknown@invalid>");
  }

  auto to_header = header->contains("To") ? header->headers_map["To"][0]->as<headers::SIPIdentityHeader>() : nullptr;

  if (to_header != nullptr && to_header->value != nullptr) {
    // Copy the identity before adding a tag: the request's To is still needed unchanged for
    // transaction matching (RFC 3261 17.2.3).
    auto to_identity = std::make_shared<SIPIdentity>(*to_header->value);

    // RFC 3261 8.2.6.2: add a To tag if the request had none.
    if (!to_identity->tags.contains("tag")) {
      to_identity->tags["tag"] = Util::generate_random_string("athena-", 10);
    }

    response->header->add("To", to_identity->to_string());
  } else {
    response->header->add("To", "<sip:unknown@invalid>;tag=" + Util::generate_random_string("athena-", 10));
  }

  if (header->contains("Call-ID")) {
    response->header->add("Call-ID", header->headers_map["Call-ID"][0]);
  } else {
    response->header->add("Call-ID", Util::generate_random_string("autogenerated-badreq-", 10));
  }
  // RFC 3261 8.2.6.2: every Via is copied, in order.
  if (header->contains("Via")) {
    for (const auto& via : header->headers_map["Via"]) response->header->add("Via", via);
  }

  if (header->contains("CSeq")) {
    response->header->add("CSeq", header->headers_map["CSeq"][0]);
  } else {
    response->header->add("CSeq", "1 " + header->request_method);
  }

  response->header->add("Allow", std::make_shared<StringHeader>("INVITE, ACK, CANCEL, OPTIONS, BYE, REFER, NOTIFY, MESSAGE, INFO"));

  return response;
}

std::string operator+(const SIPMessage& message, const std::string& str) { return message.to_string() + str; }
std::string operator+(const std::string& str, const SIPMessage& message) { return str + message.to_string(); }

